/**
 * ISO 4217 active currencies.
 *
 * The event form used to offer six hard-coded codes — GBP, USD, EUR, ZAR, NGN, KES —
 * which left an organiser in Kinshasa unable to price an event in the currency their
 * audience actually holds.
 *
 * ## This list is not a promise that a currency can be settled
 *
 * The code chosen here is passed to the payment rail at checkout
 * (`app/api/checkout/route.ts`), and the rails do not all cover the same set:
 *
 *   - **Stripe** settles roughly 135 currencies. **CDF is not one of them.** An event
 *     priced in CDF cannot be paid for by card.
 *   - **BitriPay / KODA** is the mobile-money corridor, and is how a CDF or other
 *     Central African price is actually collected.
 *
 * Listing every currency is what was asked for and is right — a promoter should be able
 * to state a price in their own money. `SETTLEABLE_BY_STRIPE` exists so a surface that
 * needs to warn about the gap can, rather than every caller re-deriving it.
 *
 * ## Fees are resolved by country, not by currency
 *
 * `shared/fees.ts` looks the buyer fee up from `constants/fees.ts` by **country code**,
 * and only `GB` is active today (`CD` is present with `active: false`). So changing the
 * currency changes the number shown to the buyer and the currency charged, and does not
 * by itself change which fee schedule applies. Adding a country to the fee config is a
 * separate, deliberate act.
 */

